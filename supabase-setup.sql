-- عطاء ولويل: جداول المنشورات وإعدادات المتجر
-- نفّذ هذا الملف مرة واحدة في Supabase > SQL Editor بعد مراجعة RLS.
-- لا يعدّل أو يحذف جداول المنتجات والأقسام الحالية.

create table if not exists public.store_posts (
  id bigint generated by default as identity primary key,
  title text not null,
  body text,
  image_url text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  id integer primary key check (id = 1),
  settings jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.store_posts enable row level security;
alter table public.store_settings enable row level security;

drop policy if exists "Public can read active store posts" on public.store_posts;
create policy "Public can read active store posts"
on public.store_posts for select
to anon, authenticated
using (active = true);

drop policy if exists "Admins manage store posts" on public.store_posts;
create policy "Admins manage store posts"
on public.store_posts for all
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Public can read store settings" on public.store_settings;
create policy "Public can read store settings"
on public.store_settings for select
to anon, authenticated
using (true);

drop policy if exists "Admins manage store settings" on public.store_settings;
create policy "Admins manage store settings"
on public.store_settings for all
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

